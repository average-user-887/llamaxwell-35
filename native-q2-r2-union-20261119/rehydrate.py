"""Materialize original path-bound build inputs in a separate directory."""
import argparse,hashlib
from pathlib import Path
p=argparse.ArgumentParser()
p.add_argument('source_mount')
p.add_argument('destination',type=Path)
args=p.parse_args()
base=Path(__file__).resolve().parent
args.destination.mkdir(parents=True,exist_ok=True)
if any(args.destination.iterdir()): p.error('destination must be empty')
if not Path(args.source_mount).is_absolute(): p.error('source_mount must be an absolute container source path')
expected={n:d for d,n in (line.split('  ',1) for line in (base/'FROZEN.sha256').read_text().splitlines())}
changed=0
for name,digest in expected.items():
    f=base/name
    if (base/(name+'.in')).exists():
        src=(base/(name+'.in')).read_bytes().replace(b'@SOURCE_MOUNT@',args.source_mount.encode())
    elif name=='build-host.log': src=(base/'build-host.txt').read_bytes()
    elif f.is_file(): src=f.read_bytes()
    else: continue  # binaries/object and disassembly are regenerated by the build
    matches=hashlib.sha256(src).hexdigest()==digest
    if not matches and not (base/(name+'.in')).exists(): raise ValueError(name)
    changed+=not matches
    target=args.destination/name
    target.write_bytes(src)
    if name.endswith('.sh'): target.chmod(0o755)
print(f'Extracted exact source and execution inputs; path-dependent original-byte differences: {changed}')
